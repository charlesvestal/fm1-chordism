// The original's factory presets as chd_patch_t rows (app/dsp/chd_presets.h): each preset applied to a new instance of
// the original (tests/ref/chordism_plugin.cpp), then every parameter read back through its get_param, so a row holds
// what the original plays, the defaults included.
//   c++ -O1 -Iapp/dsp -o ref_presets tests/ref/ref_presets.cpp && ./ref_presets > app/dsp/chd_presets.h
#include "chordism_plugin.cpp"
extern "C" {
#include "chd.h"
}

#define KEY_(id, key, lo, hi, def) {key, lo, hi},
static const struct { const char *key; int lo, hi; } P[] = {CHD_PARAMS(KEY_)};

int main()
{
    host_api_v1_t host = {};
    host.sample_rate = 44100;
    plugin_api_v2_t *api = move_plugin_init_v2(&host);
    void *probe = api->create_instance("", "");
    char buf[64];
    api->get_param(probe, "preset_count", buf, sizeof buf);
    int n = atoi(buf);
    api->destroy_instance(probe);
    if (n != CHD_NPRESET) {
        fprintf(stderr, "ref_presets: the original has %d presets, chd.h says %d\n", n, CHD_NPRESET);
        return 1;
    }
    printf("/* SPDX-License-Identifier: MIT\n * Copyright (c) 2026 Charles Vestal */\n");
    printf("/* generated by tests/ref/ref_presets.cpp from the original's presets (schwung-chordism %s): each applied "
           "to a new\n * instance, every parameter read back (chd.h CHD_PARAMS' order) */\n", "src/dsp/chordism_plugin.cpp");
    printf("const chd_patch_t CHD_PRESET[CHD_NPRESET] = {\n");
    for (int i = 0; i < n; i++) {
        void *in = api->create_instance("", "");
        snprintf(buf, sizeof buf, "%d", i);
        api->set_param(in, "preset", buf);
        api->get_param(in, "preset_name", buf, sizeof buf);
        if (!strcmp(buf, "Gypsy Lead"))               // (renamed: the scale is the Hungarian minor)
            snprintf(buf, sizeof buf, "Hungarian Lead");
        printf("    {\"%s\", {", buf);
        for (unsigned k = 0; k < sizeof P / sizeof P[0]; k++) {
            api->get_param(in, P[k].key, buf, sizeof buf);
            double v = atof(buf);
            int q = P[k].hi == 10000 ? (int)lround(v * 10000.0) : (int)lround(v);
            if (q < P[k].lo || q > P[k].hi) {
                fprintf(stderr, "ref_presets: preset %d %s = %s, out of %d..%d\n", i, P[k].key, buf, P[k].lo, P[k].hi);
                return 1;
            }
            printf("%s%d", k ? "," : "", q);
        }
        printf("}},\n");
        api->destroy_instance(in);
    }
    printf("};\n");
    return 0;
}
